import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import assert from 'node:assert/strict';
import Calculator from '../src/calculator.jsx';
import {CalculationSettings} from '../src/calculation-detail.jsx';
import {emptySheet,newCalculationRow,resolveCalculation,snapshotRecord} from '../src/calculation-sheet.js';

const sheet=emptySheet('cable');
sheet.params.base='68740';sheet.params.current='105825';
const inherited={...newCalculationRow(),name:'共用默认',specification:'YJV-3×400',length:'63.61'};
const overridden={...inherited,id:'override',name:'本行例外',overrides:{current:'90000'}};
sheet.rows=[inherited,overridden];
const project={id:'calculator-render',name:'界面验收示例',calculationSheets:{cable:sheet}};
const oldSnapshot=snapshotRecord(project,'cable',sheet,overridden);
const before=resolveCalculation('cable',sheet,overridden).result.value;
const settings=CalculationSettings({kind:'cable',sheet,onParameter:(id,value)=>{sheet.params[id]=value;},onInspectRow:()=>{}});
const descendants=node=>React.Children.toArray(node).flatMap(child=>React.isValidElement(child)?[child,...descendants(child.props.children)]:[]);
const current=descendants(settings).find(node=>node.props['aria-label']==='本表默认施工月均铜价');
assert.ok(current,'Shared price input remains directly available in formula settings');
current.props.onChange({target:{value:'100000'}});
assert.equal(resolveCalculation('cable',sheet,inherited).inputs.current,'100000');
assert.equal(resolveCalculation('cable',sheet,overridden).result.value,before);
assert.equal(oldSnapshot.source.inputs.current,'90000');
assert.equal(overridden.overrides.current,'90000');
const settingsHTML=renderToStaticMarkup(<CalculationSettings kind="cable" sheet={sheet} busy onParameter={()=>{}} onInspectRow={()=>{}}/>);
assert.match(settingsHTML,/本行例外/);assert.match(settingsHTML,/1 行使用单独设置/);
assert.match(settingsHTML,/<input[^>]*aria-label="本表默认施工月均铜价"[^>]*disabled=""/);
const markup=renderToStaticMarkup(<Calculator project={project} busy onChange={()=>{}} onPublish={()=>{}}/>).replace(/<style>[\s\S]*?<\/style>/g,'');
assert.match(markup,/公式与参数/);assert.match(markup,/保存到计算记录/);assert.match(markup,/未选择行/);
assert.doesNotMatch(markup,/aria-label="本表默认/,'Settings stay closed until requested');
assert.doesNotMatch(markup,/data-format-column="(?:selection|index)"/,'Helper columns do not expose alignment targets');
assert.match(markup,/data-format-column="specification"/,'Business columns keep alignment targets');
assert.doesNotMatch(markup,/class="cable-recognition"/,'Recognition no longer consumes a second table line');
assert.match(markup,/title="[^"]*规格识别/);
assert.match(markup,/<button[^>]*disabled=""[^>]*>[\s\S]*?保存到计算记录/);
console.log('Calculation settings preserve row overrides and snapshots; compact actions render.');
